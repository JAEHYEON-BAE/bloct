import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {importMarkdown} from '../../../Editor/src/model/importer.ts';
const header = '| subblock | number of allocated addresses | prefix length | first address | last address |';
const separator = '| --- | --- | --- | --- | --- |';
const row = '|1 | 2 | 3 | 4 | 5 |';
const valid = [header, separator, row].join('\n');
const escaped = ['\\' + header, '\\' + separator, row].join('\n');
const saved = readFileSync('/private/tmp/bloct-table-input-probe/typed.md', 'utf8');
assert.equal(saved, ['\\' + header, '\\' + separator, row].join('\n\n'));
const cases = [['valid file', valid, ['table']], ['escaped leading pipes', escaped, ['paragraph']], ['GUI typed with Enter then saved', saved, ['paragraph', 'paragraph', 'paragraph']]];
const results = cases.map(([name, source, expected]) => {
  const doc = importMarkdown(source).doc;
  const types = doc.content.content.map(node => node.type.name);
  assert.deepEqual(types, expected);
  return {name, source, types, tables: types.filter(type => type === 'table').length};
});
